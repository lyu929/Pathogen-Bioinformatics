"""Render ``reports/REPORT.md`` from pipeline results. Every number in it is computed."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import pandas as pd

from pathogenomics import __version__


def md_table(df: pd.DataFrame, index: bool = True, floatfmt: str = "{:,.2f}") -> str:
    """GitHub-flavoured Markdown table without extra dependencies."""
    frame = df.reset_index() if index else df

    def fmt(v: Any) -> str:
        if isinstance(v, bool):
            return "yes" if v else "no"
        if isinstance(v, float):
            if pd.isna(v):
                return ""
            return f"{v:,.0f}" if float(v).is_integer() and abs(v) >= 1000 else floatfmt.format(v)
        if isinstance(v, int):
            return f"{v:,}"
        return str(v).replace("|", "\\|")

    header = "| " + " | ".join(str(c) for c in frame.columns) + " |"
    sep = "| " + " | ".join("---" for _ in frame.columns) + " |"
    rows = ["| " + " | ".join(fmt(v) for v in row) + " |" for row in frame.itertuples(index=False)]
    return "\n".join([header, sep, *rows])


def metric_table(metrics: dict[str, Any]) -> str:
    """Two-column metric/value table that keeps integers as integers."""
    frame = pd.DataFrame(
        {"metric": list(metrics), "value": pd.Series(list(metrics.values()), dtype=object)}
    )
    return md_table(frame, index=False, floatfmt="{:.6g}")


def picture(stem: str, alt: str) -> str:
    return (
        "<picture>\n"
        f'  <source media="(prefers-color-scheme: dark)" srcset="figures/dark/{stem}.png">\n'
        f'  <img alt="{alt}" src="figures/light/{stem}.png">\n'
        "</picture>"
    )


def _top_table(top: pd.DataFrame) -> pd.DataFrame:
    out = top[["gene", "product", "baseMean", "log2FoldChange", "padj"]].copy().astype(object)
    out["padj"] = [("< 1e-300" if p == 0 else p) for p in top["padj"]]
    out["baseMean"] = [round(float(v)) for v in top["baseMean"]]
    out["log2FoldChange"] = [round(float(v), 2) for v in top["log2FoldChange"]]
    return out


def write_report(results: dict[str, Any], cfg: dict[str, Any], path: str | Path) -> Path:
    q, a, an, pg, rs, st = (
        results[k] for k in ("qc", "assembly", "annotation", "pangenome", "rnaseq", "structure")
    )
    th = cfg["thresholds"]
    lines: list[str] = [
        "# Results report",
        "",
        f"_Generated by `pathogenomics run` (v{__version__}). Do not edit by hand - rerun the pipeline._",
        "",
        "All inputs are the outputs I produced in Galaxy (usegalaxy.org) and NCBI Datasets during BIOL 4640; ",
        "this report re-derives every result with the tested Python code in `src/pathogenomics/`.",
        "",
        "## 1. Read QC and trimming",
        "",
        f"Re-implementing Cutadapt's quality-trimming algorithm and re-running it on the BR-Tn1 reads reproduces the "
        f"Galaxy Cutadapt {q['cutadapt_version']} report **{'exactly' if q['trim_matches_cutadapt'] else 'NOT exactly'}**:",
        "",
        md_table(q["trim_validation"]),
        "",
        f"The independent FASTQ statistics agree with FastQC ({q['fastqc_reads']:,} reads, {q['fastqc_gc']}% GC in FastQC; "
        f"{q['raw']['reads']:,} reads, {q['raw']['gc_percent']}% GC here; largest per-base mean-quality difference "
        f"{q['fastqc_max_mean_quality_diff']:.2g} Phred).",
        "",
        picture(q["figure"], "Per-base quality before and after trimming"),
        "",
        "FastQC module calls for every library inspected in the course:",
        "",
        md_table(
            q["fastqc_table"][
                ["total_sequences", "sequence_length", "gc_percent", "failed_modules"]
            ]
        ),
        "",
        md_table(q["cutadapt_table"]),
        "",
        "## 2. Genome assembly (P. aeruginosa isolates, SPAdes)",
        "",
        f"Contigs >= {cfg['assembly']['min_contig']} bp. Assembly sizes fall inside the "
        f"{a['ref_min'] / 1e6:.2f}-{a['ref_max'] / 1e6:.2f} Mb range of the {a['ref_n']} complete P. aeruginosa "
        "RefSeq genomes downloaded for comparison.",
        "",
        md_table(a["table"].drop(columns=["ng50"])),
        "",
        picture(a["figure"], "Nx curves"),
        "",
        "Other assemblies from the course (all contigs):",
        "",
        md_table(a["other"].drop(columns=["ng50"])),
        "",
        "## 3. Annotation and marker screening (S. aureus)",
        "",
        md_table(an["summary"]),
        "",
        f"methicillin resistance (`mecA` encoding PBP2a) is present in: {', '.join(an['mrsa'])}; absent in: {', '.join(an['mssa'])}.",
        "",
        picture(an["figure"], "Marker presence heatmap"),
        "",
        "Why markers are called from product names, not gene symbols - RefSeq reuses symbols for unrelated genes:",
        "",
        md_table(an["collisions"], index=False),
        "",
        "## 4. Pangenome (Roary, 4 clinical isolates + PA14)",
        "",
        md_table(pg["partitions"]),
        "",
        f"{pg['n_clusters']:,} gene clusters across {pg['n_genomes']} genomes; only {pg['accessory']} are accessory. "
        f"Accessory-gene Jaccard distances among the clinical isolates range "
        f"{pg['isolate_dist_range'][0]:.2f}-{pg['isolate_dist_range'][1]:.2f}, versus >= {pg['reference_dist_min']:.2f} to PA14.",
        "",
        picture(pg["figures"][0], "Pangenome rarefaction"),
        "",
        picture(pg["figures"][1], "Accessory genome heatmap"),
        "",
        "## 5. RNA-seq differential expression",
        "",
        f"Thresholds: BH-adjusted p < {th['alpha']} and |log2FC| >= {th['min_abs_lfc']}. PyDESeq2 is run on the same "
        "featureCounts tables used in Galaxy and compared with the Galaxy (R) DESeq2 output.",
        "",
    ]
    for name, r in rs.items():
        conc = r["concordance"]
        lines += [
            f"### {r['title']}",
            "",
            md_table(r["libraries"].drop(columns=["top_gene_pct"], errors="ignore")),
            "",
            metric_table(conc),
            "",
            f"{r['direction']['up']} genes up and {r['direction']['down']} down in `{r['test']}` relative to `{r['reference']}`. "
            "Top hits:",
            "",
            md_table(_top_table(r["top"]), floatfmt="{:.3g}"),
            "",
            picture(r["figures"][0], f"Volcano plot {name}"),
            picture(r["figures"][1], f"Concordance {name}"),
            picture(r["figures"][2], f"PCA {name}"),
            "",
        ]
    b = st["af3_bands"]
    lines += [
        "## 6. Protein structure",
        "",
        f"**AlphaFold 3 model of M. tuberculosis Zur/FurB (Rv2359, {st['af3_len']} aa).** Mean pLDDT {b['mean_plddt']}; "
        f"{100 * (b['very_high'] + b['confident']):.0f}% of residues >= 70; mean PAE {st['pae_mean']} Angstrom.",
        "",
        md_table(st["af3"]),
        "",
        "> AlphaFold Server output and the figure derived from it are provided under and subject to the "
        "[AlphaFold Server Output Terms of Use](https://alphafoldserver.com/output-terms) "
        "(non-commercial use; see `data/structure/alphafold3_zur_Rv2359/TERMS_OF_USE.md`).",
        "",
        picture(st["figures"][0], "AlphaFold 3 confidence"),
        "",
        "**M. abscessus LuxR-family regulator vs M. tuberculosis DosR (AlphaFold DB models).**",
        "",
        metric_table(st["homolog"]),
        "",
        "Rigid bodies found by iterative superposition (2 Angstrom cutoff):",
        "",
        md_table(st["bodies"], index=False),
        "",
        picture(st["figures"][1], "pLDDT profiles"),
        "",
        f"**SARS-CoV-2 spike, {cfg['structure']['spike_a_label']} vs {cfg['structure']['spike_b_label']} (chain {cfg['structure']['spike_chain']}).**",
        "",
        metric_table(st["spike"]),
        "",
        f"Differences at residues modelled in 6VXX (Wuhan numbering); receptor-binding domain (319-541): "
        f"{', '.join(st['spike_rbd']['label'])}. Full list: `results/structure_spike_differences.tsv`. "
        "Both entries are engineered ectodomain constructs, so differences can include construct design as well as lineage mutations.",
        "",
    ]
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
